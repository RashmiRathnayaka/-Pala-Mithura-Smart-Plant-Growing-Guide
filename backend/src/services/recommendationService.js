/**
 * Recommendation workflow (spec §7–§8):
 *  1. user submits report → 2. backend calls AI → 3. AI draft saved (ai_generated)
 *  4. queued (pending_review) → 5–6. instructor accepts / modifies / rejects
 *  7. published to user → 8. user notified. Every step is written to the audit log.
 */
const { Recommendation, ProblemReport, Plant, UserPlant, Counter } = require('../models');
const { REC_STATUS } = require('../utils/constants');
const ApiError = require('../utils/ApiError');
const ai = require('./ai/aiService');
const { RecommendationContentSchema } = require('./ai/schema');
const audit = require('./auditService');
const notifications = require('./notificationService');

async function nextCode() {
  const n = await Counter.next('recommendation');
  return `REC-${String(n).padStart(6, '0')}`;
}

async function loadAiInputs(report) {
  const plant = await Plant.findById(report.plant).populate('pestsAndDiseases').lean();
  if (!plant) throw ApiError.notFound('Plant not found');
  const userPlant = report.userPlant ? await UserPlant.findById(report.userPlant).lean() : null;
  return { plant, userPlant };
}

/** Steps 2–4: run the AI for a report and put the result in the review queue. */
async function createFromReport(report) {
  report.status = 'analyzing';
  await report.save();

  const { plant, userPlant } = await loadAiInputs(report);
  const rec = new Recommendation({
    recommendationCode: await nextCode(),
    user: report.user,
    plant: report.plant,
    userPlant: report.userPlant,
    report: report._id,
    status: REC_STATUS.AI_GENERATED,
  });

  let aiOk = true;
  try {
    const { content, meta } = await ai.generateRecommendation({
      plant,
      userPlant,
      report: report.toObject(),
      language: report.language,
    });
    rec.aiOutput = content;
    rec.aiMeta = meta;
    await rec.save();
    await audit.record({
      entityType: 'recommendation',
      entityId: rec._id,
      action: 'ai_generated',
      note: `${meta.provider}/${meta.model}${meta.isTestOutput ? ' (test output)' : ''}`,
      after: content,
    });
  } catch (err) {
    aiOk = false;
    console.error('[ai] generation failed:', err.message);
    rec.aiOutput = null;
    rec.aiMeta = { provider: ai.providerInfo().provider, error: String(err.message).slice(0, 500), generatedAt: new Date() };
    await rec.save();
    await audit.record({
      entityType: 'recommendation',
      entityId: rec._id,
      action: 'ai_failed',
      note: 'AI analysis failed – sent to an instructor for manual review',
    });
  }

  // Step 4 – into the instructor queue.
  rec.status = REC_STATUS.PENDING_REVIEW;
  await rec.save();
  await audit.record({ entityType: 'recommendation', entityId: rec._id, action: 'queued_for_review' });

  report.status = aiOk ? 'analyzed' : 'ai_failed';
  report.recommendation = rec._id;
  await report.save();

  if (aiOk) await notifications.notifyRecommendationReady(rec);
  await notifications.notifyInstructorsNewItem(rec);
  return rec;
}

/** Re-run the AI for an item still waiting for review (e.g. after a transient AI failure). */
async function regenerate(recId, actor) {
  const rec = await Recommendation.findById(recId);
  if (!rec) throw ApiError.notFound('Recommendation not found');
  if (rec.status !== REC_STATUS.PENDING_REVIEW || rec.review.decision) {
    throw ApiError.conflict('Only recommendations waiting for review can be regenerated', 'INVALID_STATE');
  }
  const report = await ProblemReport.findById(rec.report);
  const { plant, userPlant } = await loadAiInputs(report);
  const before = rec.aiOutput;
  const { content, meta } = await ai.generateRecommendation({ plant, userPlant, report: report.toObject(), language: report.language });
  rec.aiOutput = content;
  rec.aiMeta = meta;
  await rec.save();
  report.status = 'analyzed';
  await report.save();
  await audit.record({ entityType: 'recommendation', entityId: rec._id, action: 'ai_generated', actor, note: 'Regenerated by reviewer', before, after: content });
  return rec;
}

/** Step 6 – instructor decision. Validated entirely on the server. */
async function review(recId, instructor, input) {
  const { decision } = input;
  const existing = await Recommendation.findById(recId);
  if (!existing) throw ApiError.notFound('Recommendation not found');
  if (existing.status !== REC_STATUS.PENDING_REVIEW) {
    throw ApiError.conflict('This recommendation has already been reviewed', 'ALREADY_REVIEWED');
  }

  const reviewFields = {
    'review.decision': decision,
    'review.reviewer': instructor._id,
    'review.comment': input.comment || '',
    'review.reviewedAt': new Date(),
  };
  let finalRecommendation = null;
  let status;

  if (decision === 'accepted') {
    if (!existing.aiOutput) throw ApiError.badRequest('There is no AI recommendation to accept. Use "modify" to write one.');
    finalRecommendation = existing.aiOutput.toObject ? existing.aiOutput.toObject() : existing.aiOutput;
    status = REC_STATUS.ACCEPTED;
  } else if (decision === 'modified') {
    const parsed = RecommendationContentSchema.safeParse(input.content);
    if (!parsed.success) {
      throw ApiError.badRequest(
        'Modified recommendation is invalid',
        parsed.error.issues.map((i) => ({ field: `content.${i.path.join('.')}`, message: i.message }))
      );
    }
    if (!parsed.data.summary && !parsed.data.suggestedActions.length) {
      throw ApiError.badRequest('A modified recommendation needs a summary or at least one suggested action');
    }
    finalRecommendation = parsed.data;
    reviewFields['review.changeExplanation'] = input.changeExplanation;
    status = REC_STATUS.MODIFIED;
  } else if (decision === 'rejected') {
    reviewFields['review.rejectionReason'] = input.rejectionReason;
    reviewFields['review.alternativeRecommendation'] = input.alternativeRecommendation || '';
    reviewFields['review.additionalInfoRequested'] = input.additionalInfoRequested || '';
    status = REC_STATUS.REJECTED;
  } else {
    throw ApiError.badRequest('decision must be accepted, modified or rejected');
  }

  // Atomic transition: only succeeds if still pending (prevents two instructors deciding at once).
  const rec = await Recommendation.findOneAndUpdate(
    { _id: recId, status: REC_STATUS.PENDING_REVIEW },
    { $set: { ...reviewFields, status, finalRecommendation } },
    { returnDocument: 'after', runValidators: true }
  );
  if (!rec) throw ApiError.conflict('This recommendation has already been reviewed', 'ALREADY_REVIEWED');

  await audit.record({
    entityType: 'recommendation',
    entityId: rec._id,
    action: decision,
    actor: instructor,
    note: input.changeExplanation || input.rejectionReason || input.comment || '',
    before: existing.aiOutput,
    after: { finalRecommendation, review: rec.review },
  });

  if (input.publish !== false) return publish(rec._id, instructor);
  return rec;
}

/** Step 7–8 – publish to the user and notify them. */
async function publish(recId, actor) {
  const rec = await Recommendation.findOneAndUpdate(
    { _id: recId, status: { $in: [REC_STATUS.ACCEPTED, REC_STATUS.MODIFIED, REC_STATUS.REJECTED] } },
    { $set: { status: REC_STATUS.PUBLISHED, publishedAt: new Date(), publishedBy: actor._id } },
    { returnDocument: 'after' }
  );
  if (!rec) {
    const exists = await Recommendation.exists({ _id: recId });
    if (!exists) throw ApiError.notFound('Recommendation not found');
    throw ApiError.conflict('Only reviewed recommendations can be published', 'INVALID_STATE');
  }
  await audit.record({
    entityType: 'recommendation',
    entityId: rec._id,
    action: 'published',
    actor,
    after: { finalRecommendation: rec.finalRecommendation, decision: rec.review.decision },
  });
  await notifications.notifyReviewCompleted(rec);
  return rec;
}

/**
 * What the farmer may see. Unreviewed AI output is always marked preliminary, and is hidden
 * once an instructor rejects it, so it can never be mistaken for approved advice.
 */
function toUserView(recDoc) {
  const rec = recDoc.toObject ? recDoc.toObject() : recDoc;
  const published = rec.status === REC_STATUS.PUBLISHED;
  const decision = rec.review?.decision || null;
  const view = {
    _id: rec._id,
    recommendationCode: rec.recommendationCode,
    status: published ? REC_STATUS.PUBLISHED : rec.status === REC_STATUS.AI_GENERATED ? REC_STATUS.AI_GENERATED : REC_STATUS.PENDING_REVIEW,
    plant: rec.plant,
    userPlant: rec.userPlant,
    report: rec.report,
    createdAt: rec.createdAt,
    updatedAt: rec.updatedAt,
    aiAvailable: !!rec.aiOutput,
    aiIsTestOutput: !!rec.aiMeta?.isTestOutput,
    isInstructorVerified: published && (decision === 'accepted' || decision === 'modified'),
    preliminary: null,
    final: null,
    review: null,
    userViewedAt: rec.userViewedAt || null,
  };
  if (!published) {
    view.preliminary = rec.aiOutput || null;
  } else {
    view.review = {
      decision,
      comment: rec.review.comment,
      changeExplanation: rec.review.changeExplanation,
      rejectionReason: rec.review.rejectionReason,
      alternativeRecommendation: rec.review.alternativeRecommendation,
      additionalInfoRequested: rec.review.additionalInfoRequested,
      reviewedAt: rec.review.reviewedAt,
      reviewerName: rec.review.reviewer && rec.review.reviewer.name ? rec.review.reviewer.name : undefined,
    };
    view.publishedAt = rec.publishedAt;
    if (decision !== 'rejected') view.final = rec.finalRecommendation;
  }
  return view;
}

module.exports = { createFromReport, regenerate, review, publish, toUserView };
